#!/bin/sh
# ЧТО АВТОМАТИКА ДЕЛАЕТ — И НА ЧТО ОНА ПРИ ЭТОМ УКАЗЫВАЕТ.
#
# Обычный обход отвечает на первый вопрос и молчит про второй. 30.08 полный
# обход боевой машины дал идеальную картину: ноль упавших юнитов, всё в
# автозапуске, контейнеры с политикой перезапуска, таймеры отрабатывают,
# сертификат свежий. И ровно в это время каждые пять минут задача исправно
# ВОССТАНАВЛИВАЛА правило пересылки на адрес, который уже отпущен и отдан
# другому клиенту провайдера. Зелёная картина держалась НАДЁЖНОСТЬЮ
# автоматики, а не правильностью её параметров.
#
# Запускать только на самой машине или через stdin — так строка не проходит
# через разбор обёртки и не теряет кавычки:
#
#   ssh <host> sh -s < autonomy-audit.sh
#
# Коды возврата:
#   0  расхождений не нашлось
#   1  нашлось: смотреть отмеченное словом ГНИЛЬ
#   2  снять состояние не удалось
set -u

FOUND=0
mark() { FOUND=1; printf '  ГНИЛЬ: %s\n' "$1"; }

command -v systemctl >/dev/null 2>&1 || { echo "нет systemctl — снять состояние нечем"; exit 2; }

printf 'ОБХОД АВТОНОМНОСТИ: %s, %s\n\n' "$(hostname)" "$(date -Is)"

# ---------------------------------------------------------------- окно
# Любой счётчик трафика, рукопожатий и «последнего раза» обнуляется при
# перезапуске. Пока не знаешь аптайм — не имеешь права говорить «никогда».
UP=$(cut -d. -f1 /proc/uptime 2>/dev/null || echo 0)
printf 'ОКНО НАБЛЮДЕНИЯ\n'
printf '  аптайм %s ч — все счётчики ниже считают ТОЛЬКО с этого момента,\n' "$((UP / 3600))"
printf '  и «ноль» в них означает «не за эти часы», а не «никогда»\n\n'

# ------------------------------------------------------- enabled != active
# is-active говорит про сейчас, is-enabled — про после перезагрузки. Юнит
# может быть поднят руками и не вернуться сам; обратное тоже бывает.
printf 'ЮНИТЫ: автозапуск против текущего состояния\n'
systemctl list-units --type=service --state=running --no-legend --no-pager 2>/dev/null \
| awk '{print $1}' | while read -r u; do
    en=$(systemctl is-enabled "$u" 2>/dev/null)
    case "$en" in
        disabled|static-disabled) ;;
        *) continue ;;
    esac
    # Служба может подниматься сокетом, а не своим юнитом: тогда сама она
    # честно disabled, но после перезагрузки вернётся. Без этой проверки
    # шлюз кричит на штатную активацию по сокету (поймано на ssh.service).
    sock=$(systemctl is-enabled "${u%.service}.socket" 2>/dev/null)
    [ "$sock" = "enabled" ] && continue
    printf '  ГНИЛЬ: %s работает, но НЕ вернётся после перезагрузки (%s)\n' "$u" "$en"
    echo x >> /tmp/.autonomy_rot
done
[ -f /tmp/.autonomy_rot ] && { FOUND=1; rm -f /tmp/.autonomy_rot; }
printf '  упавших юнитов: %s\n\n' "$(systemctl --failed --no-legend --no-pager 2>/dev/null | grep -c .)"

# ------------------------------------------------------- контейнеры
if command -v docker >/dev/null 2>&1; then
    printf 'КОНТЕЙНЕРЫ: политика перезапуска\n'
    for c in $(docker ps --format '{{.Names}}' 2>/dev/null); do
        p=$(docker inspect -f '{{.HostConfig.RestartPolicy.Name}}' "$c" 2>/dev/null)
        printf '  %-24s %s\n' "$c" "$p"
        case "$p" in no|"") mark "$c без политики перезапуска — после отказа не вернётся" ;; esac
    done
    printf '\n'
fi

# ------------------------------------------- протухшие адреса в правилах
# Главная проверка. Правило пересылки на адрес, которого у машины больше
# нет, не может совпасть НИКОГДА, а задача по расписанию исправно его
# пересоздаёт — и тем маскирует переезд.
if command -v iptables >/dev/null 2>&1; then
    printf 'ПРАВИЛА ПЕРЕСЫЛКИ: адрес назначения против адресов машины\n'
    MINE=$(ip -4 -o addr show 2>/dev/null | awk '{print $4}' | cut -d/ -f1 | tr '\n' ' ')
    printf '  адреса машины: %s\n' "$MINE"
    iptables -t nat -L PREROUTING -n -v 2>/dev/null | awk 'NR>2 && NF' | while read -r l; do
        pkts=$(echo "$l" | awk '{print $1}')
        dst=$(echo "$l" | awk '{print $9}')
        case "$dst" in
            ""|0.0.0.0/0|*[!0-9.]*) continue ;;
        esac
        case " $MINE " in
            *" $dst "*) ;;
            *) printf '  ГНИЛЬ: правило на %s — такого адреса у машины НЕТ (пакетов %s)\n' "$dst" "$pkts"
               echo x >> /tmp/.autonomy_rot ;;
        esac
    done
    [ -f /tmp/.autonomy_rot ] && { FOUND=1; rm -f /tmp/.autonomy_rot; }
    printf '\n'
fi

# --------------------------------------- периодические задачи без замка
# Причина отказа по памяти 28.08. Пять задач с интервалом в минуту, ни одна
# не защищена взаимным исключением; каждая поднимает рантайм приложения.
# Пока быстро — не пересекаются и не видны. При замедлении запуск обгоняет
# завершение, копии копятся, и машина умирает не от одной задачи, а от их
# наложения.
printf 'ПЕРИОДИЧЕСКИЕ ЗАДАЧИ: интервал против взаимного исключения\n'
MIN=0
crontab -l 2>/dev/null | grep -v '^[[:space:]]*#' | grep -v '^[[:space:]]*$' | while read -r line; do
    case "$line" in
        '* * * * *'*)
            case "$line" in
                *flock*|*lockfile*|*setlock*) ;;
                *) printf '  ГНИЛЬ: раз в минуту и БЕЗ замка: %s\n' "$(echo "$line" | cut -c1-90)"
                   echo x >> /tmp/.autonomy_rot ;;
            esac ;;
    esac
done
[ -f /tmp/.autonomy_rot ] && { FOUND=1; rm -f /tmp/.autonomy_rot; }
MIN=$(crontab -l 2>/dev/null | grep -c '^\* \* \* \* \*')
printf '  минутных задач всего: %s\n' "$MIN"
[ "$MIN" -ge 3 ] && printf '  сложить их худшее время выполнения и сравнить с минутой\n'
printf '\n'

# ------------------------------------------------- кто трогает журналы
# Уборщик диска усекает журналы и тем уничтожает улики, по которым ведётся
# разбор. Пустой поиск по журналу после этого читается как «событий не было».
printf 'ЖУРНАЛЫ: не усечён ли источник улик\n'
df -h / 2>/dev/null | awk 'NR==2{printf "  диск %s занято\n", $5}'
# Пустой журнал сам по себе НЕ подозрителен: скрипт, который пишет только
# при расхождении, молчит месяцами, и это норма. Подозрителен ровно один
# случай — пустой файл, у которого ЕСТЬ ротированные копии: писать в него
# было что, и содержимое унесли. Так уборщик диска стёр улики за текущие
# сутки, а поиск по ним прочитался как «событий не было».
for f in /var/log/*/*.log /var/log/*.log; do
    [ -f "$f" ] || continue
    [ -s "$f" ] && continue
    rot=$(ls "$f".1 "$f".1.gz "$f".2.gz 2>/dev/null | grep -c .)
    [ "$rot" -eq 0 ] && continue
    printf '  ОПУСТОШЁН: %s (изменён %s, копий %s) — улики брать из ротированных\n' \
           "$f" "$(date -r "$f" '+%H:%M' 2>/dev/null)" "$rot"
done
printf '\n'

if [ "$FOUND" -ne 0 ]; then
    printf 'ВЕРДИКТ: автоматика жива, но указывает не туда.\n'
    printf 'Отмеченное словом ГНИЛЬ править НЕ на месте, а в источнике: адрес\n'
    printf 'живёт в константе скрипта И в конфигурации выдачи — искать поиском\n'
    printf 'по всему дереву, иначе задача по расписанию восстановит мёртвое.\n'
    exit 1
fi

printf 'ВЕРДИКТ: расхождений не нашлось. Шлюз не проверил и проверить не может:\n'
printf '  1. Куда указывают ПАРАМЕТРЫ ВЫДАЧИ клиентам (адрес, порт, домен).\n'
printf '  2. Доходит ли выданный конфиг до цели — это меряется у клиента.\n'
exit 0
