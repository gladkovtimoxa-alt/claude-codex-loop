#!/bin/sh
# На каком УРОВНЕ отказал недоступный узел: сеть, ядро или процессы.
#
# Зачем: «сервер не отвечает» — это три разные аварии с тремя разными
# лечениями, и по одному ping их не различить. Мы уже потеряли круг,
# приняв задушенную нехваткой памяти машину за отфильтрованную сетью.
#
# Проб ровно три, и каждая снимает СВОЙ уровень:
#
#   1. ping                  — доходит ли до узла хоть что-то
#   2. заведомо ЗАКРЫТЫЙ порт — отвечает ли ЯДРО осознанно.
#      Честный мгновенный отказ доказывает, что фильтра нет: файрвол так
#      не умеет, он молчит одинаково на всех портах и выбирает весь таймаут.
#   3. рабочий порт, чтение БАЙТОВ — жив ли USERLAND.
#      Здесь нельзя ограничиться установкой соединения: приём соединения
#      делает ядро, и задушенная машина принимает его точно так же, как
#      здоровая. Отличает их только то, отдала ли служба хоть один байт.
#      Проба, дающая одинаковый ответ при успехе и при провале, — не проба.
#
# Таблица прочтения:
#   ping нет, порты молчат             -> сеть/маршрут/машина выключена
#   ping есть, ВСЕ порты молчат        -> фильтр между нами и узлом
#   закрытый отказал, рабочий ОТДАЛ    -> узел здоров, копать в другом месте
#   закрытый отказал, рабочий МОЛЧИТ   -> ядро живо, процессам не достаётся
#                                         ресурсов: память в ноль, load в сотнях
#
# Последний случай лечится СНЯТИЕМ ПИТАНИЯ, а не мягкой перезагрузкой:
# мягкая требует, чтобы userland отработал остановку сервисов, а он и есть
# то, что стоит колом — система повиснет в шатдауне. И факт нажатия кнопки
# не доказывает ребут: доказывает только uptime после подъёма.
#
#   host-alive-layer.sh <адрес> [рабочий_порт] [заведомо_закрытый_порт]
set -u

HOST="${1:?укажи адрес}"
LIVE="${2:-443}"
DEAD="${3:-3306}"   # порт, на котором наружу заведомо никто не слушает

# Уровень 2. ACCEPT | REFUSED | SILENT
# Отказ и фильтр различаются ТОЛЬКО по времени ответа: честный отказ приходит
# мгновенно, фильтр выбирает весь таймаут. Кода возврата для этого мало.
probe_tcp() {
    _t0=$(date +%s)
    if timeout 8 sh -c "echo > /dev/tcp/$HOST/$1" 2>/dev/null; then
        echo ACCEPT; return
    fi
    _t1=$(date +%s)
    if [ $((_t1 - _t0)) -lt 3 ]; then echo REFUSED; else echo SILENT; fi
}

# Уровень 3. BYTES | NOBYTES — отдала ли служба хоть что-то прикладное.
probe_bytes() {
    case "$1" in
        22)
            # sshd здоровается первым: ждём строку версии, ничего не посылая.
            _b=$(timeout 10 sh -c "head -c 32 < /dev/tcp/$HOST/22" 2>/dev/null)
            [ -n "$_b" ] && echo BYTES || echo NOBYTES
            ;;
        *)
            # http/https: важен сам факт кода ответа, любой сгодится.
            _c=$(curl -s -k -o /dev/null -w '%{http_code}' --max-time 12 \
                 "https://$HOST:$1/" 2>/dev/null)
            [ -z "$_c" ] || [ "$_c" = "000" ] && _c=$(curl -s -o /dev/null \
                 -w '%{http_code}' --max-time 12 "http://$HOST:$1/" 2>/dev/null)
            if [ -n "$_c" ] && [ "$_c" != "000" ]; then echo "BYTES($_c)"; else echo NOBYTES; fi
            ;;
    esac
}

printf 'Уровень отказа узла %s\n\n' "$HOST"

if ping -c 2 -W 3 "$HOST" >/dev/null 2>&1 || ping -n 2 -w 3000 "$HOST" >/dev/null 2>&1; then
    PING=yes
else
    PING=no
fi

R_DEAD=$(probe_tcp "$DEAD")
R_LIVE=$(probe_tcp "$LIVE")
if [ "$R_LIVE" = ACCEPT ]; then R_BYTES=$(probe_bytes "$LIVE"); else R_BYTES=NOBYTES; fi

printf '  ping ................... %s\n' "$PING"
printf '  порт %s закрытый ....... %s\n' "$DEAD" "$R_DEAD"
printf '  порт %s соединение ..... %s\n' "$LIVE" "$R_LIVE"
printf '  порт %s байты .......... %s\n' "$LIVE" "$R_BYTES"
printf '\n'

case "$R_BYTES" in BYTES*) GOT=yes ;; *) GOT=no ;; esac

if [ "$GOT" = yes ]; then
    printf 'ВЕРДИКТ: узел ЗДОРОВ — служба ответила прикладными данными.\n'
    printf 'Отказ, если он есть, не на этом узле и не на этом порту.\n'
elif [ "$PING" = no ] && [ "$R_LIVE" != ACCEPT ]; then
    printf 'ВЕРДИКТ: узел недостижим целиком — маршрут, сеть или машина выключена.\n'
    printf 'Смотреть панель хостера: запущена ли машина вообще.\n'
elif [ "$R_DEAD" = SILENT ] && [ "$R_LIVE" = SILENT ]; then
    printf 'ВЕРДИКТ: молчат ВСЕ порты, включая заведомо закрытый — это ФИЛЬТР.\n'
    printf 'Ядро отдало бы отказ на закрытом порту; раз молчит, отвечает не оно.\n'
elif [ "$R_DEAD" = REFUSED ] && [ "$R_LIVE" = ACCEPT ]; then
    printf 'ВЕРДИКТ: ядро ЖИВО (закрытый порт честно отказал), userland МЁРТВ\n'
    printf '(соединение принято, но ни байта прикладных данных).\n'
    printf 'Это нехватка ресурсов: проверить free и load, если войдёшь.\n'
    printf 'Лечение: СНЯТИЕ ПИТАНИЯ. Мягкая перезагрузка на такой машине зависает.\n'
    printf 'После подъёма сверить uptime — иначе не узнаешь, был ли ребут вообще.\n'
else
    printf 'ВЕРДИКТ: смешанная картина, однозначного уровня нет.\n'
    printf 'Повторить пробу: отказ и фильтр различаются по ВРЕМЕНИ ответа.\n'
fi
