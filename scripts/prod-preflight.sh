#!/bin/sh
# ШЛЮЗ ПЕРЕД ДЕЙСТВИЕМ НА БОЕВОЙ МАШИНЕ.
#
# Не памятка. Сам снимает состояние и ОТКАЗЫВАЕТ кодом возврата, если
# действовать нельзя. Памятку надо вспомнить — а вспомнить не получается:
# 28.08 я знал, что тяжёлая команда опасна на тесной машине, и всё равно
# запустил консоль фреймворка на узле с load 99. Она повисла на 25 минут и
# стала частью аварии. Знание не сработало, шлюз бы сработал.
#
#   prod-preflight.sh <host> [ssh-key] [--heavy]
#
#   --heavy  проверять по строгому порогу: для команд, поднимающих рантайм
#            приложения целиком (консоль фреймворка, сборка, дамп базы)
#
# Коды возврата:
#   0  можно действовать
#   1  НЕЛЬЗЯ: машина не потянет, читать данные лёгким путём
#   2  не удалось снять состояние — это тоже «нельзя», а не «наверное можно»
set -u

HOST="${1:?укажи хост}"
KEY="${2:-}"
MODE="${3:-}"

[ -n "$KEY" ] && KEYOPT="-i $KEY" || KEYOPT=""

# Порог свободной памяти. Обычной команде хватает 80 МБ; команде, которая
# поднимает приложение целиком, нужно с запасом на само приложение.
if [ "$MODE" = "--heavy" ]; then MIN_AVAIL=250; else MIN_AVAIL=80; fi

# ВАЖНО: таймаут ставится и на удалённой стороне тоже. Обрыв на своей
# стороне НЕ убивает процесс там — он остаётся сиротой и продолжает
# жрать ресурсы, то есть диагностика превращается в часть аварии.
OUT=$(timeout 30 ssh -o BatchMode=yes -o ConnectTimeout=15 $KEYOPT "$HOST" \
      "timeout 20 sh -c 'uptime; free -m | sed -n 2p; nproc; swapon --show=SIZE --noheadings | head -1'" 2>&1)

if [ $? -ne 0 ] || [ -z "$OUT" ]; then
    printf 'ШЛЮЗ: НЕ СНЯТО состояние %s\n' "$HOST"
    printf '%s\n' "$OUT"
    printf '\nЭто «нельзя», а не «наверное можно». Непроверенное состояние\n'
    printf 'боевой машины — не основание действовать.\n'
    exit 2
fi

LOAD=$(printf '%s\n' "$OUT" | sed -n 1p | sed 's/.*load average: //' | cut -d, -f1 | tr -d ' ')
AVAIL=$(printf '%s\n' "$OUT" | sed -n 2p | awk '{print $NF}')
CORES=$(printf '%s\n' "$OUT" | sed -n 3p | tr -d ' ')
SWAP=$(printf '%s\n' "$OUT" | sed -n 4p | tr -d ' ')
[ -n "$SWAP" ] || SWAP="НЕТ"

printf 'ШЛЮЗ перед действием на %s\n\n' "$HOST"
printf '  load (1 мин) ....... %s при %s ядрах\n' "$LOAD" "$CORES"
printf '  свободно памяти .... %s МБ (порог %s)\n' "$AVAIL" "$MIN_AVAIL"
printf '  своп ............... %s\n' "$SWAP"
printf '\n'

VERDICT=0

# Сравнение дробных чисел через awk: в sh его нет.
if awk "BEGIN{exit !($LOAD > $CORES)}"; then
    printf '  СТОП: load выше числа ядер — машина уже не справляется.\n'
    VERDICT=1
fi

if [ "$AVAIL" -lt "$MIN_AVAIL" ] 2>/dev/null; then
    printf '  СТОП: свободной памяти меньше порога.\n'
    VERDICT=1
fi

if [ "$SWAP" = "НЕТ" ]; then
    printf '  ВНИМАНИЕ: свопа нет. Ядру некуда вытеснять — вместо замедления\n'
    printf '            будет мгновенный обвал, и мягкая перезагрузка не пройдёт.\n'
fi

printf '\n'
if [ "$VERDICT" -ne 0 ]; then
    printf 'ВЕРДИКТ: НЕ ДЕЙСТВОВАТЬ тяжёлой командой.\n'
    printf 'Читать данные напрямую (клиент БД, файл), а не через рантайм приложения.\n'
    exit 1
fi

printf 'ВЕРДИКТ: действовать можно. Осталось руками, шлюз это не проверит:\n'
printf '  1. Правишь файл? Скачай боевую версию и сравни ПОСТРОЧНО.\n'
printf '     В расхождении должны быть ТОЛЬКО твои строки. Размер не годится.\n'
printf '  2. Бэкап с говорящим именем: <файл>.bak-<что>-<дата>.\n'
printf '  3. Команду ОТКАТА назови вслух ДО правки, а не после.\n'
printf '  4. Таймаут — на удалённой стороне, иначе обрыв оставит сироту.\n'
exit 0
